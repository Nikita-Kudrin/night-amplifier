    /// Void-and-cluster threshold ranks for a `side`-square toroidal tile.
    ///
    /// Energy is a Gaussian splat per set pixel, so the tightest cluster is the set pixel
    /// of highest energy and the largest void the empty pixel of lowest. A seed pattern
    /// is relaxed until moving its tightest cluster lands it back where it was; ranks
    /// below the seed's count come from emptying it cluster first, ranks above from
    /// filling voids, and past half the minority flips to the empty pixels.
    pub fn void_and_cluster(side: usize) -> Vec<u16> {
        const SIGMA: f64 = 1.5;
        let n = side * side;
        let kernel: Vec<f64> = (0..n)
            .map(|i| {
                let wrapped = |d: usize| d.min(side - d) as f64;
                let (dy, dx) = (wrapped(i / side), wrapped(i % side));
                (-(dx * dx + dy * dy) / (2.0 * SIGMA * SIGMA)).exp()
            })
            .collect();
        let splat = |energy: &mut [f64], at: usize, sign: f64| {
            let (py, px) = (at / side, at % side);
            for y in 0..side {
                let row = &kernel[((y + side - py) % side) * side..][..side];
                for x in 0..side {
                    energy[y * side + x] += sign * row[(x + side - px) % side];
                }
            }
        };
        let energy_of = |pattern: &[bool]| {
            let mut energy = vec![0.0; n];
            for i in (0..n).filter(|&i| pattern[i]) {
                splat(&mut energy, i, 1.0);
            }
            energy
        };
        // Ties go to the lowest index, which is what keeps the output reproducible.
        let tightest_cluster = |pattern: &[bool], energy: &[f64]| {
            (0..n)
                .filter(|&i| pattern[i])
                .fold(None, |best: Option<usize>, i| match best {
                    Some(b) if energy[b] >= energy[i] => Some(b),
                    _ => Some(i),
                })
                .unwrap()
        };
        let largest_void = |pattern: &[bool], energy: &[f64]| {
            (0..n)
                .filter(|&i| !pattern[i])
                .fold(None, |best: Option<usize>, i| match best {
                    Some(b) if energy[b] <= energy[i] => Some(b),
                    _ => Some(i),
                })
                .unwrap()
        };

        let mut state = 0x9E37_79B9_7F4A_7C15u64;
        let seeded = n / 10;
        let mut pattern = vec![false; n];
        let mut placed = 0;
        while placed < seeded {
            state ^= state << 13;
            state ^= state >> 7;
            state ^= state << 17;
            let i = (state % n as u64) as usize;
            if !pattern[i] {
                pattern[i] = true;
                placed += 1;
            }
        }
        let mut energy = energy_of(&pattern);
        loop {
            let cluster = tightest_cluster(&pattern, &energy);
            pattern[cluster] = false;
            splat(&mut energy, cluster, -1.0);
            let void = largest_void(&pattern, &energy);
            pattern[void] = true;
            splat(&mut energy, void, 1.0);
            if void == cluster {
                break;
            }
        }

        let mut rank = vec![0u16; n];
        let seed = pattern.clone();
        let mut energy = energy_of(&pattern);
        for r in (0..seeded).rev() {
            let i = tightest_cluster(&pattern, &energy);
            pattern[i] = false;
            splat(&mut energy, i, -1.0);
            rank[i] = r as u16;
        }
        let mut pattern = seed;
        let mut energy = energy_of(&pattern);
        for r in seeded..n / 2 {
            let i = largest_void(&pattern, &energy);
            pattern[i] = true;
            splat(&mut energy, i, 1.0);
            rank[i] = r as u16;
        }
        let mut empty: Vec<bool> = pattern.iter().map(|&p| !p).collect();
        let mut energy = energy_of(&empty);
        for r in n / 2..n {
            let i = tightest_cluster(&empty, &energy);
            empty[i] = false;
            splat(&mut energy, i, -1.0);
            rank[i] = r as u16;
        }
        rank
    }

    #[test]
    fn the_table_is_the_generators_output() {
        let ranks = void_and_cluster(64);
        let expected: Vec<u8> = ranks.iter().map(|&r| (r >> 4) as u8).collect();
        let actual: Vec<u8> = BLUE_NOISE_64.iter().flatten().copied().collect();
        if actual != expected {
            let fmt = |v: &[u8]| v.iter().map(|x| format!("{x:>3}")).collect::<Vec<_>>().join(", ");
            for row in expected.chunks(64) {
                println!("    [{},\n     {}],", fmt(&row[..32]), fmt(&row[32..]));
            }
            panic!("BLUE_NOISE_64 differs from the generator; the replacement is printed above");
        }
    }

    /// A value used more or less often than the rest biases the dither toward one
    /// threshold, which shows up as a faint tint rather than as a crash.
    #[test]
    fn every_threshold_is_used_by_exactly_sixteen_pixels() {
        let mut uses = [0u32; 256];
        for &v in BLUE_NOISE_64.iter().flatten() {
            uses[v as usize] += 1;
        }
        assert!(uses.iter().all(|&u| u == 16), "{uses:?}");
    }
